#!/bin/sh
# Embeds collector/rpu_collector.py into the Swift sources (so the app and rpu-probe
# carry the exact script they pipe to remote hosts). Run after editing the collector;
# scripts/mac.sh runs it automatically and a unit test fails if it is out of date.
set -eu
cd "$(dirname "$0")/.."
out=Sources/RemotePUCore/Generated/CollectorScript.swift
mkdir -p "$(dirname "$out")"
{
  echo '// GENERATED by scripts/gen-collector.sh from collector/rpu_collector.py — do not edit.'
  echo 'public enum CollectorScript {'
  echo '    public static let source = #"""'
  cat collector/rpu_collector.py
  echo '"""#'
  echo '}'
} > "$out.tmp"
mv "$out.tmp" "$out"
echo "wrote $out"
